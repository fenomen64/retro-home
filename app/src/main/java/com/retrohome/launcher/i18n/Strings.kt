    val langName: String get() = if (lang == Lang.RU) "Русский" else "English"

    fun packName(id: String) = when (id) {
        "off" -> sfxOff; "retro" -> sfxRetro; "crystal" -> sfxCrystal; "click" -> sfxClick; else -> sfxSoft
    }

    fun trackName(id: String) = when (id) {
        "off" -> sfxOff; "chiptune" -> musicChiptune; "lofi" -> musicLofi; "custom" -> musicCustom; else -> musicAmbient
    }

    fun themeName(id: String) = when (id) { "oled" -> themeOled; "graphite" -> themeGraphite; "light" -> themeLight; else -> themeNight }

    fun accentName(id: String) = when (id) {
        "orange" -> accentOrange; "gold" -> accentGold; "green" -> accentGreen; "teal" -> accentTeal
        "blue" -> accentBlue; "purple" -> accentPurple; "pink" -> accentPink; else -> accentCoral
    }

    fun hapticsName(id: String) = when (id) { "off" -> hapticsOff; "medium" -> hapticsMedium; "strong" -> hapticsStrong; else -> hapticsLight }

    fun sortName(id: String) = when (id) { "recent" -> sortRecent; "playtime" -> sortPlaytime; else -> sortName }

    /** «3 ч 20 мин», «45 мин», «меньше минуты». */
    fun duration(ms: Long): String {
        val min = ms / 60_000
        return when {
            min < 1 -> lessMinute
            min < 60 -> minutes.format(min)
            else -> hoursMinutes.format(min / 60, min % 60)
        }
    }

    /** «сегодня», «вчера», «5 дн. назад» или дата. */
    fun ago(time: Long, now: Long = System.currentTimeMillis()): String {
        val zone = java.time.ZoneId.systemDefault()
        val day = java.time.Instant.ofEpochMilli(time).atZone(zone).toLocalDate()
        val days = java.time.temporal.ChronoUnit.DAYS.between(day, java.time.Instant.ofEpochMilli(now).atZone(zone).toLocalDate())
        return when {
            days <= 0 -> today
            days == 1L -> yesterday
            days < 30 -> daysAgo.format(days)
            else -> java.time.format.DateTimeFormatter.ofPattern("d MMM yyyy", java.util.Locale(if (lang == Lang.RU) "ru" else "en")).format(day)
        }
    }

    fun sourceName(src: String?) = when (src) {
        "wikidata" -> wikidataSource; "eshop" -> eshopSource; else -> wikiSource
    }
